const eraButtons = [...document.querySelectorAll(".era-button")];
const milestoneTrack = document.querySelector(".milestone-track");
const progress = document.querySelector(".era-progress");
const story = document.querySelector(".heritage-story");
const storyImage = document.querySelector(".story-image");
const storyCaption = document.querySelector(".story-image-caption");
const storyYear = document.querySelector(".story-year");
const storyTitle = document.querySelector(".story-title");
const storyDescription = document.querySelector(".story-description");
let selectedEra = 1940;

function showMilestone(milestone) {
  storyYear.textContent = `${milestone.year} · ${milestone.place}`;
  storyTitle.textContent = milestone.title;
  storyDescription.textContent = milestone.description;
  storyCaption.textContent = milestone.place;
  storyImage.alt = milestone.alt;
  storyImage.style.opacity = "0";
  storyImage.addEventListener(
    "load",
    () => {
      storyImage.style.opacity = "1";
    },
    { once: true },
  );
  storyImage.src = milestone.image;
  if (storyImage.complete && storyImage.naturalWidth > 0) storyImage.style.opacity = "1";
  story.dataset.year = milestone.year;
}

function selectEra(era) {
  selectedEra = Number(era);
  const activeIndex = eraButtons.findIndex((button) => Number(button.dataset.era) === selectedEra);
  eraButtons.forEach((button, index) => {
    const active = index === activeIndex;
    button.setAttribute("aria-pressed", String(active));
    button.tabIndex = active ? 0 : -1;
  });
  progress.style.width = `${(activeIndex / (eraButtons.length - 1)) * 100}%`;

  const eraMilestones = milestones[selectedEra];
  milestoneTrack.replaceChildren(
    ...eraMilestones.map((milestone, index) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "milestone-button";
      button.dataset.year = milestone.year;
      button.setAttribute("aria-pressed", String(index === 0));
      button.textContent = milestone.year;
      button.addEventListener("click", () => {
        milestoneTrack.querySelectorAll(".milestone-button").forEach((item) => {
          item.setAttribute("aria-pressed", String(item === button));
        });
        showMilestone(milestone);
      });
      return button;
    }),
  );
  showMilestone(eraMilestones[0]);
}

eraButtons.forEach((button) => {
  button.addEventListener("click", () => selectEra(button.dataset.era));
  button.addEventListener("keydown", (event) => {
    if (!["ArrowLeft", "ArrowRight", "Home", "End"].includes(event.key)) return;
    event.preventDefault();
    const currentIndex = eraButtons.indexOf(button);
    const nextIndex =
      event.key === "Home"
        ? 0
        : event.key === "End"
          ? eraButtons.length - 1
          : (currentIndex + (event.key === "ArrowRight" ? 1 : -1) + eraButtons.length) %
            eraButtons.length;
    eraButtons[nextIndex].focus();
    eraButtons[nextIndex].click();
  });
});

selectEra(selectedEra);
